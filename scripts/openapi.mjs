#!/usr/bin/env node
// openapi.json is the spec as the API serves it at https://storiesfly.com/openapi.json.
// openapi.yaml is the same document in YAML, made from it by this script.
//
//   node scripts/openapi.mjs sync    write openapi.yaml from openapi.json
//   node scripts/openapi.mjs check   validate both files against the OpenAPI 3.1 schema,
//                                    and fail when the YAML is not the JSON
//
// To update the spec: replace openapi.json with the new file, run `sync`, then `check`.
// Nothing here uses the network.

import { readFile, writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import { fileURLToPath } from "node:url";
import { Validator } from "@seriousme/openapi-schema-validator";
import { parse, stringify } from "yaml";

const jsonPath = fileURLToPath(new URL("../openapi.json", import.meta.url));
const yamlPath = fileURLToPath(new URL("../openapi.yaml", import.meta.url));

const HEADER =
  "# The same document as openapi.json, made from it by `npm run openapi:sync`.\n" +
  "# Do not edit this file: change openapi.json and run the script.\n";

async function readJson() {
  return JSON.parse(await readFile(jsonPath, "utf8"));
}

function toYaml(spec) {
  return HEADER + stringify(spec, { lineWidth: 0 });
}

async function validate(label, spec) {
  const result = await new Validator().validate(spec);
  if (!result.valid) {
    console.error(`${label} is not a valid OpenAPI document:`);
    console.error(JSON.stringify(result.errors, null, 2));
    return false;
  }
  return true;
}

const command = process.argv[2];

if (command === "sync") {
  const spec = await readJson();
  await writeFile(yamlPath, toYaml(spec));
  console.log("wrote openapi.yaml");
} else if (command === "check") {
  const fromJson = await readJson();
  const yamlText = await readFile(yamlPath, "utf8");
  const fromYaml = parse(yamlText);

  let ok = true;
  ok = (await validate("openapi.json", fromJson)) && ok;
  ok = (await validate("openapi.yaml", fromYaml)) && ok;

  if (!isDeepStrictEqual(fromJson, fromYaml)) {
    console.error("openapi.yaml is not the same document as openapi.json. Run `npm run openapi:sync`.");
    ok = false;
  } else if (yamlText !== toYaml(fromJson)) {
    console.error("openapi.yaml is not what the script writes. Run `npm run openapi:sync`.");
    ok = false;
  }

  if (!ok) process.exit(1);
  console.log("openapi.json and openapi.yaml are valid and in step");
} else {
  console.error("usage: node scripts/openapi.mjs sync|check");
  process.exit(2);
}
